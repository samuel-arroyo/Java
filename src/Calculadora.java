// Calculadora basica para operaciones con dos numeros enteros

public class Calculadora {

    //Suma dos numeros enteros num1 y num2

    public int sune(int num1,int num2)
    {
        return num1 + num2;
    }

    // resta dos numeros enteros num1 y num2

    public int resta(int num1,int num2)
    {
        return num1 - num2;
    }

    // Multiplca dos numeros enteros num1 y num2

    public int multiplicacion(int num1,int num2)
    {
        return num1 * num2;
    }

    // Divide dos numeros enteros num1 y num2

    public int divide (int num1,int num2)
    {
        return num1 / num2;
    }
}
